-- 입퇴사자 관리 — 퇴사자의 휴직복귀일 컬럼 추가
-- Supabase Dashboard > SQL Editor 에서 실행하세요 (몇 번 실행해도 안전 · idempotent)
-- 기존 employees 데이터는 전혀 손대지 않음 — nullable 컬럼 추가만.
-- ─────────────────────────────────────────────────────────────────────────────

-- 같은 정산월 안에서 휴직복귀 후 퇴사한 직원의 휴직복귀일. 한 사람이 휴직복귀와
-- 퇴사를 모두 가질 수 있으므로 별도 행을 만들지 않고 같은 employees 행에 저장한다.
-- 값이 있으면 헥토코인 인정 시작일 = 이 날짜, 인정 종료일 = exit_date(퇴사일).
-- 값이 없는 일반 퇴사자는 기존 계산(입사일~퇴사일)을 그대로 쓴다.
alter table public.employees
  add column if not exists return_date date;

comment on column public.employees.return_date is
  '퇴사자의 휴직복귀일(같은 정산월 안 복귀 후 퇴사한 경우에만 사용). 헥토코인 인정 시작일 = 이 날짜, 인정 종료일 = exit_date';
